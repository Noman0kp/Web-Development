// MATH.ABS FUNCTION GIVES THE ABSOLUTE VALUE. i.e. NO NEGATIVE. WORKS FOR INTEGERS AND DECIMALS BOTH.

console.log(Math.abs(-5));
console.log(Math.abs(8));
console.log(Math.abs(-1.44)); 

// MIN MAX FUNCTION WILL GIVE THE MAX. AND MIN. FROM THE GIVEN ARGUMENTS. MULTIPLE ARGUMENTS COULD BE GIVEN. WORKS WITH DECIMALS TOO.

console.log(Math.max(5,17));
console.log(Math.min(-5,1));
console.log(Math.max(5,17,29,0,111.112));

// MATH.POW(a,b) WILL GIVE a TO RAISED TO POWER b. WORKS WITH DECIMALS ALSO.

console.log(Math.pow(2,5));
console.log(Math.pow(1.4142135623730951,2));
console.log(Math.pow(-2,-5));

// MATH.SQRT(a) WILL GIVE THE SQUARE ROOT OF a. WORKS WITH DECIMALS TOO.

console.log(Math.sqrt(9));
console.log(Math.sqrt(2));
console.log(Math.sqrt(16.256));

// MATH.CBRT(a) WILL GIVE THE CUBE ROOT OF a. WORKS WITH DECIMALS TOO.

console.log(Math.cbrt(8));
console.log(Math.cbrt(11));
console.log(Math.cbrt(8.8));

// LOG FUNCTION

console.log(Math.log2(8));
console.log(Math.log10(10000));
console.log(Math.log(14)); // IN THIS CASE, IT'LL TAKE THE BASE AS e.

// FLOOR AND CEILING (THESE ARE VERY USEFUL IN MAKING INTEGERS FROM DECIMAL NUMBER)

console.log(Math.floor(3.2));
console.log(Math.floor(-3.2));
console.log(Math.ceil(3.2));
console.log(Math.ceil(-3.2));

// MATH.RANDOM() 
// THIS WILL PRINT A RANDOM REAL NUMBER BETWEEN 0 AND 1 EVERYTIME WE RUN IT (EXCLUDING 0 & 1). AND EVERYTIME THE NUMBER IS DIFFERENT FROM THE PREVIOUS.

console.log(Math.random()); 

