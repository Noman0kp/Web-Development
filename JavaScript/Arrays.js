// IN JAVASCRIPT, ARRAY CAN HOLD ELEMENTS OF DIFFERENT DATA TYPES, UNLIKE C++ WHERE AN ARRAY CAN ONLY HOLD ELEMENTS OF THE SAME DATA TYPE.

console.log("ARRAY WITH DIFFERENT DATA TYPES : ");

let arr3 = [1, "Hello", true, 3.14, 'A', [1, 2, 3],]; 
console.log(arr3); 


// MAKING A 2D ARRAY IN JAVASCRIPT :

console.log("2D ARRAY EXAMPLE : ");
let arr4 = [[1, 2, 3], [4, 5, 6], [7, 8, 9]];
console.log(arr4); // THIS WILL PRINT THE 2D ARRAY.

// EACH ARRAY INSIDE THE MAIN ARRAY IS CALLED A ROW, AND EACH ELEMENT INSIDE THE ROW IS CALLED A COLUMN. WE CAN ACCESS ELEMENTS OF THE 2D ARRAY USING TWO INDEXES, FIRST FOR THE ROW AND SECOND FOR THE COLUMN.

console.log("ACCESSING ELEMENTS OF THE 2D ARRAY : ");

console.log("First element : " + arr4[0][0]); // THIS WILL PRINT THE FIRST ELEMENT OF THE FIRST ROW, WHICH IS 1.

console.log("Middle element : " + arr4[1][1]); // THIS WILL PRINT THE MIDDLE ELEMENT OF THE SECOND ROW, WHICH IS 5.

// UNLIKE C++, IN JAVASCRIPT WE CAN HAVE JAGGED ARRAYS, WHICH ARE ARRAYS OF ARRAYS WITH DIFFERENT LENGTHS.

console.log("JAGGED ARRAY EXAMPLE : ");
let arr5 = [[1, 2], [3, 4, 5], [6]];
console.log(arr5); // THIS WILL PRINT THE JAGGED ARRAY.

// 2D ARRAYS CAN ALSO CONTAIN ELEMENTS OF DIFFERENT DATA TYPES, JUST LIKE 1D ARRAYS.

console.log("2D ARRAY WITH DIFFERENT DATA TYPES : ");
let arr6 = [[1, "Hello"], [true, 3.14], ['A', [1, 2, 3]]];
console.log(arr6); // THIS WILL PRINT THE 2D ARRAY WITH DIFFERENT DATA TYPES.