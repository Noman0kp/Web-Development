let arr = [1, 2, 3, 4, 5];

console.log(arr); // THIS WILL PRINT THE ENTIRE ARRAY.

// IN C++ WE HAD VECTOR FOR DYNAMIC ARRAYS, IN JAVASCRIPT WE HAVE ARRAYS WHICH ARE DYNAMIC BY DEFAULT. i.e. WE CAN ADD OR REMOVE ELEMENTS FROM THE ARRAY WITHOUT ANY ISSUE. UNLIKE C++.

arr.push(6); // THIS WILL ADD 6 TO THE END OF THE ARRAY.
console.log("PUSH " + arr); 

arr.pop(); // THIS WILL REMOVE THE LAST ELEMENT FROM THE ARRAY.
console.log("POP " + arr);

arr.unshift(0); // THIS WILL ADD 0 TO THE BEGINNING OF THE ARRAY.
console.log("UNSHIFT " + arr);

arr.shift(); // THIS WILL REMOVE THE FIRST ELEMENT FROM THE ARRAY.
console.log("SHIFT " + arr);

// WE CAN ACCEESS ELEMENTS OF THE ARRAY USING INDEXES, JUST LIKE IN C++.

console.log("iNDEX 0 :" + arr[0]); // THIS WILL PRINT THE FIRST ELEMENT OF THE ARRAY.

// WE CAN ALSO USE FOR LOOPS TO ITERATE THROUGH THE ARRAY.

console.log("ITERATING THROUGH THE ARRAY USING A FOR LOOP : ");

let size = arr.length; // THIS WILL GIVE THE SIZE OF THE ARRAY.

for(let i = 0; i<size; i++) {
    console.log(arr[i]); // THIS WILL PRINT EACH ELEMENT OF THE ARRAY.
}


// MAKING A CONST ARRAY... : 

console.log("CONST ARRAY EXAMPLE : ");

const arr2 = [10, 20, 30, 40, 50];
console.log("CONST ARRAY : " + arr2);
arr2.push(60); 
arr2[0] = 5; 
console.log("MODIFIED CONST ARRAY : " + arr2); 

// UNLIKE CONST VARIABLES, CONST ARRAYS CAN BE MODIFIED. WE CAN ADD OR REMOVE ELEMENTS FROM A CONST ARRAY, BUT WE CANNOT REASSIGN THE ENTIRE ARRAY TO A NEW VALUE.

